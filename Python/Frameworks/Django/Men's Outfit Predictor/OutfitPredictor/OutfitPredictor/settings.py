def _env_bool(name, default=False):
    """Parse explicit boolean values and reject typos instead of enabling a setting."""
    value = os.environ.get(name)
    if value is None:
        return default
    normalized = value.strip().lower()
    if normalized in ("1", "true", "yes", "on"):
        return True
    if normalized in ("0", "false", "no", "off"):
        return False
    raise ImproperlyConfigured("%s must be a boolean value." % name)


def _env_csv(name):
    """Read a comma-separated list of non-empty values."""
    return [
        part.strip()
        for part in os.environ.get(name, "").split(",")
        if part.strip()
    ]


